import { expect, test } from "@playwright/test";

test.use({ channel: process.env.PLAYWRIGHT_CHANNEL });

test("doctor creates a personal template and records an immutable document from the agenda", async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  const credentials = { email: "henrique.lima@clinicaaurora.com", password: "ChangeMe123!" };
  const login = await request.post("http://127.0.0.1:8080/auth/login", { data: credentials });
  expect(login.ok()).toBeTruthy();
  const auth = await login.json();
  const headers = { Authorization: `Bearer ${auth.accessToken}` };
  const appointments = await (await request.get("http://127.0.0.1:8080/appointments", { headers })).json();
  const appointment = appointments.items.find((item: { id: string }) => item.id === "eeeeeeee-eeee-eeee-eeee-eeeeeeeeeeee");
  expect(appointment).toBeTruthy();
  const record = await request.post(`http://127.0.0.1:8080/appointments/${appointment.id}/clinical-record`, { headers, data: { chiefComplaint: "Acompanhamento" } });
  expect(record.ok()).toBeTruthy();

  await page.goto("/");
  await page.getByLabel("E-mail", { exact: true }).fill(credentials.email);
  await page.getByLabel("Senha", { exact: true }).fill(credentials.password);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await page.getByRole("button", { name: "Cadastro de receituários", exact: true }).click();
  await page.getByRole("button", { name: "Novo receituário", exact: true }).click();
  const title = `Orientações ${Date.now()}`;
  await page.getByLabel("Título", { exact: true }).fill(title);
  await page.getByLabel("Conteúdo / orientações", { exact: true }).fill("Paciente: {{paciente}}\nRetornar para acompanhamento.");
  await page.getByLabel("Disponibilidade").selectOption("personal");
  await expect(page.getByRole("region", { name: "Editor de receituário" })).toBeVisible();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Salvar cadastro", exact: true }).click();
  await expect(page.getByText(title, { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("clinical-catalog.png"), fullPage: true });
  await page.getByRole("button", { name: "Agenda", exact: true }).click();
  const day = await page.evaluate(value => {
    const date = new Date(value);
    return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  }, appointment.startAt);
  await page.getByLabel("Data da agenda").fill(day);
  await page.getByRole("button", { name: "Dia", exact: true }).click();
  await page.getByRole("button", { name: /Editar consulta:/ }).first().click({ button: "right" });
  await page.getByRole("button", { name: "Abrir prontuário", exact: true }).click();
  await page.getByRole("button", { name: "Receituário e documentos", exact: true }).click();
  await expect(page.getByText("Histórico clínico e documentos", { exact: true })).toBeVisible();
  await expect(page.getByText("Arquivos do paciente", { exact: true })).toBeVisible();
  await expect(page.getByRole("dialog")).toHaveCount(1);
  await expect(page.getByRole("navigation", { name: "Opções do atendimento" })).toBeInViewport();
  const historyPanel = await page.getByRole("region", { name: "Histórico do paciente", exact: true }).boundingBox();
  const editorPanel = await page.getByRole("region", { name: "Digitação do prontuário", exact: true }).boundingBox();
  expect(historyPanel).toBeTruthy();
  expect(editorPanel).toBeTruthy();
  expect(editorPanel!.x).toBeGreaterThanOrEqual(historyPanel!.x + historyPanel!.width);
  await page.screenshot({ path: testInfo.outputPath("clinical-split.png"), fullPage: true });
  await page.getByLabel("Modelo / cadastro").selectOption({ label: `Geral / ${title} (pessoal)` });
  await page.getByLabel("Forma de assinatura").selectOption("DigitalMock");
  page.once("dialog", dialog => dialog.dismiss());
  await page.keyboard.press("Escape");
  await expect(page.getByLabel("Forma de assinatura")).toBeVisible();
  await page.getByRole("button", { name: "Registrar no histórico", exact: true }).click();
  await expect(page.getByText(/ASSINATURA DIGITAL SIMULADA — SEM VALIDADE/)).toBeVisible();
  await expect(page.getByText("Paciente: {{paciente}}", { exact: false })).not.toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("clinical-document.png"), fullPage: true });
  const entries = await (await request.get(`http://127.0.0.1:8080/appointments/${appointment.id}/clinical-entries`, { headers })).json();
  expect(entries).toHaveLength(1);
  expect(entries[0].title).toBe(title);
  expect(entries[0].signatureMode).toBe("DigitalMock");
  expect(entries[0].content).not.toContain("{{paciente}}");
  await page.getByRole("button", { name: "Fechar", exact: true }).last().click();
  await page.getByRole("button", { name: "Fechar", exact: true }).last().click();
  await page.getByRole("button", { name: "Pacientes", exact: true }).click();
  await page.getByRole("button", { name: "Prontuarios", exact: true }).first().click();
  await page.getByRole("button", { name: "Abrir prontuário", exact: true }).click();
  await expect(page.getByRole("button", { name: "Receituário e documentos", exact: true })).toBeVisible();
  await expect(page.getByText(title, { exact: true })).toBeVisible();
});
