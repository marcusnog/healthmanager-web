// Only the phone parameter accepts the encoded form of a plus sign.
const frontendRules = Object.entries(frontendRoutes).map(([template, methods]) => ({
  path: new RegExp(`^${template.replace(/\{\w+\}/g, (parameter) =>
    parameter === "{phone}" ? "(?:\\+|%2[Bb])?[0-9]+" : "[A-Za-z0-9_-]+",
  )}$`),
  methods: new Set(methods.split(" ")),
}));

// Keep provider callbacks at their existing URLs. The API validates the Meta
// verification challenge and authenticates webhook POSTs using their signatures.
export function isPublicBackendRoute(method: string, pathname: string): boolean {
  if (pathname === "/whatsapp/webhook") return method === "GET" || method === "POST";
  if (/^\/webhooks\/payments\/(Asaas|MercadoPago|Stripe)$/i.test(pathname)) {
    return method === "POST";
  }

  return frontendRules.some((rule) => rule.methods.has(method) && rule.path.test(pathname));
}
